#!/usr/bin/env node
/**
 * Writes `src/lib/languages/X86/generated` from the tables described in
 * `docs/design/x86-documentation.md`. The output is committed, so this runs when NASM or blink is
 * updated, not as part of the build:
 *
 *   node scripts/x86-docs-generate.mjs [--fetch]
 *
 * `--fetch` downloads the two prose sources into `.cache/x86-docs` the first time. Everything else
 * is read out of `emulators/`, which means the instruction table always describes the assembler
 * this editor actually ships rather than a snapshot of some other NASM.
 *
 * What comes out is deliberately dumb: lists and records, no curation. Which instructions are worth
 * a page, which syscalls a beginner needs and what the registers mean are decisions, and decisions
 * live in `X86-documentation.ts` next to the hand written prose.
 */

import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import {
    cached,
    expandTemplate,
    isTemplate,
    normaliseOperand,
    parseInsref,
    parseOpcodes,
    projectRoot,
    readBlinkSyscalls,
    readNasmDirectives,
    readNasmFlags,
    readNasmNames,
    readNasmPreprocessorDirectives,
    readNasmRegisters,
    readNasmStandardMacros,
    readNasmTable,
    readNasmTokens,
    readConditionCodes
} from './x86-docs/sources.mjs'

const outDir = join(projectRoot, 'src/lib/languages/X86/generated')
const fetchAllowed = process.argv.includes('--fetch')

/** Assembler pseudo-ops. They are directives that happen to live in the instruction table. */
const PSEUDO = /^(d[bwdqtoyz]|res[bwdqtoyz]|incbin|equ)$/

/**
 * Flags that say something to a reader of the documentation. Everything else in the table is
 * matching and encoding bookkeeping (`SM1`, `AR0`, `ND`, `BND`, `JCC_HINT`), which describes how
 * NASM chooses an encoding rather than what the instruction does.
 */
const NOTABLE_FLAGS = new Set([
    'LOCK',
    'LOCK1',
    'NOLONG',
    'LONG',
    'PRIV',
    'SMM',
    'UNDOC',
    'OBSOLETE',
    'NEVER',
    'NOP',
    'FPU'
])

const header = (what, sources) =>
    `/**
 * ${what}
 *
 * Generated by \`node scripts/x86-docs-generate.mjs\`; edit that script, never this file.
 *
${sources.map((line) => ` * ${line}`).join('\n')}
 */
`

/** Stable, compact, and diffable: one line per record so a regeneration shows what moved. */
function serialise(value) {
    return JSON.stringify(value)
}

// --- read ----------------------------------------------------------------------------------------

const accepted = readNasmNames()
const conditions = readConditionCodes()
const table = readNasmTable()
const flagMeanings = readNasmFlags()
const tokens = readNasmTokens()
const directives = readNasmDirectives()
const standardMacros = readNasmStandardMacros()
const registers = readNasmRegisters()
const preprocessor = readNasmPreprocessorDirectives()
const syscalls = readBlinkSyscalls()
const insref = parseInsref(
    await cached('insref.src', { fetch: fetchAllowed }),
    accepted,
    conditions
)
const opcodes = parseOpcodes(await cached('x86_64.xml', { fetch: fetchAllowed }))

// --- instructions --------------------------------------------------------------------------------

/** A template row (`Jcc`) is the entry for every name it expands to. */
const tableFor = new Map()
for (const [mnemonic, entry] of table.byMnemonic) {
    const names = isTemplate(mnemonic, accepted)
        ? expandTemplate(mnemonic, accepted, conditions)
        : [mnemonic]
    for (const name of names) {
        const merged = tableFor.get(name) ?? { sections: new Set(), forms: [] }
        for (const section of entry.sections) merged.sections.add(section)
        merged.forms.push(...entry.forms)
        tableFor.set(name, merged)
    }
}

const groupOf = (flag) => flagMeanings.get(flag)?.group

/**
 * Flags NASM files under FEATURE that are not instruction set extensions: processor modes, the
 * encodings NASM can be told to avoid, and the "do not use this" markers. They are notes, and
 * listing them beside `SSE2` would suggest an extension a reader could look up.
 */
const NOT_EXTENSIONS = new Set([
    'PROT',
    'PRIV',
    'SMM',
    'UNDOC',
    'OBSOLETE',
    'NEVER',
    'NOP',
    'VEX',
    'EVEX'
])

/**
 * One entry per operand shape. The table lists a shape once per encoding, so `add r/m32,imm8`
 * appears several times with different bytes, and again as an alias the disassembler ignores. A
 * reader wants the shape, the oldest processor that has it, and anything notable about it.
 */
function formsOf(entry) {
    const byShape = new Map()
    for (const form of entry.forms) {
        const operands = form.operands.map(normaliseOperand)
        const cpu = form.flags.find((flag) => groupOf(flag) === 'cpu') ?? ''
        const features = form.flags.filter(
            (flag) => groupOf(flag) === 'feature' && !NOT_EXTENSIONS.has(flag)
        )
        const notes = form.flags.filter((flag) => NOTABLE_FLAGS.has(flag))
        const key = operands.join(',')
        const shape = byShape.get(key)
        if (!shape) {
            byShape.set(key, { operands, cpu, features, notes: new Set(notes) })
            continue
        }
        // The same shape can have a second encoding on a later processor: `setg r/m8` is a P6
        // instruction that APX re-encodes to take a `{zu}` prefix. What it needs is what its oldest
        // encoding needs, so a newer encoding must not add its extension to the shape.
        if (cpuIndex(cpu) < cpuIndex(shape.cpu)) {
            shape.cpu = cpu
            shape.features = features
        }
        for (const note of notes) shape.notes.add(note)
    }
    return [...byShape.values()].map((shape) => {
        // A shape that exists in both modes collects `LONG` from its long mode encoding and
        // `NOLONG` from its 32 bit one, which together say nothing.
        if (shape.notes.has('LONG') && shape.notes.has('NOLONG')) {
            shape.notes.delete('LONG')
            shape.notes.delete('NOLONG')
        }
        return {
            operands: shape.operands,
            cpu: shape.cpu,
            features: [...shape.features],
            notes: [...shape.notes]
        }
    })
}

/** The oldest processor that can run any form of the instruction, in the table's own order. */
const CPU_ORDER = [...flagMeanings.entries()]
    .filter(([, meaning]) => meaning.group === 'cpu')
    .map(([name]) => name)

const cpuIndex = (cpu) => {
    const index = CPU_ORDER.indexOf(cpu)
    return index === -1 ? Number.POSITIVE_INFINITY : index
}

function lowestCpu(forms) {
    let best = ''
    let bestIndex = Number.POSITIVE_INFINITY
    for (const form of forms) {
        if (cpuIndex(form.cpu) < bestIndex) {
            bestIndex = cpuIndex(form.cpu)
            best = form.cpu
        }
    }
    return best
}

/**
 * The heading the instruction belongs under. A mnemonic can appear in two of NASM's sections, with
 * `push es` filed under segment handling and the rest of `push` under the stack, so the section
 * that holds most of its forms is the one that names it.
 */
function dominantSection(entry) {
    const counts = new Map()
    for (const form of entry.forms) counts.set(form.section, (counts.get(form.section) ?? 0) + 1)
    let best = ''
    let bestCount = 0
    for (const [section, count] of counts) {
        if (count > bestCount) {
            best = section
            bestCount = count
        }
    }
    return best
}

/** Extensions every form needs, so that `movapd` is SSE2 and `add` is not APX. */
function commonFeatures(forms) {
    if (forms.length === 0) return []
    return forms
        .map((form) => form.features)
        .reduce((shared, features) => shared.filter((feature) => features.includes(feature)))
}

const instructions = accepted
    .filter((name) => !PSEUDO.test(name))
    .sort()
    .map((name) => {
        const entry = tableFor.get(name)
        const forms = entry ? formsOf(entry) : []
        return {
            name,
            section: entry ? dominantSection(entry) : '',
            cpu: lowestCpu(forms),
            features: commonFeatures(forms),
            summary: opcodes.get(name) ?? '',
            forms
        }
    })

/**
 * NASM spells the operand size into some names (`retq`, `leavew`, `stosq`) that the appendix
 * documents under one base name. The mapping is written out rather than derived by stripping the
 * last letter, because that rule is wrong at least once: `aadd` is the APX atomic add, not `aad`.
 * Every base is checked below, so a NASM update that renames one of them fails the run.
 */
const DESCRIPTION_ALIASES = {
    retd: 'ret',
    retq: 'ret',
    retw: 'ret',
    retnd: 'retn',
    retnq: 'retn',
    retnw: 'retn',
    retfd: 'retf',
    retfq: 'retf',
    retfw: 'retf',
    enterd: 'enter',
    enterq: 'enter',
    enterw: 'enter',
    leaved: 'leave',
    leaveq: 'leave',
    leavew: 'leave',
    iretq: 'iret',
    loopd: 'loop',
    loopq: 'loop',
    loopw: 'loop',
    looped: 'loope',
    loopeq: 'loope',
    loopew: 'loope',
    loopned: 'loopne',
    loopneq: 'loopne',
    loopnew: 'loopne',
    loopnzd: 'loopnz',
    loopnzq: 'loopnz',
    loopnzw: 'loopnz',
    loopzd: 'loopz',
    loopzq: 'loopz',
    loopzw: 'loopz',
    // The string instructions: one entry covers the byte, word and dword spellings, and the qword
    // one long mode added belongs with them.
    movsq: 'movsb',
    cmpsq: 'cmpsb',
    lodsq: 'lodsb',
    stosq: 'stosb',
    scasq: 'scasb',
    movsxb: 'movsx',
    movsxw: 'movsx',
    movzxb: 'movzx',
    movzxw: 'movzx',
    movzxd: 'movzx',
    jrcxz: 'jecxz',
    int03: 'int3'
}

const descriptions = {}
for (const instruction of instructions) {
    const alias = DESCRIPTION_ALIASES[instruction.name]
    if (alias && !insref.byMnemonic.has(alias)) {
        throw new Error(`alias ${instruction.name} points at ${alias}, which has no description`)
    }
    const entry = insref.byMnemonic.get(alias ?? instruction.name)
    if (!entry) continue
    descriptions[instruction.name] = { title: entry.title, description: entry.description }
}

// --- write ---------------------------------------------------------------------------------------

mkdirSync(outDir, { recursive: true })

const NASM_SOURCE = [
    'Instruction forms, sections, flags and mnemonics: NASM 3.00 (`emulators/x86/wasm_nasm/nasm`),',
    'SPDX-License-Identifier: BSD-2-Clause, Copyright 1996-2025 The NASM Authors.'
]

writeFileSync(
    join(outDir, 'x86Instructions.ts'),
    `${header(
        'Every instruction the vendored NASM accepts, with the operand shapes it accepts them in.',
        [
            ...NASM_SOURCE,
            'One line summaries: the Opcodes project (https://github.com/Maratyszcza/Opcodes),',
            'SPDX-License-Identifier: BSD-2-Clause, Copyright (c) 2017 Facebook Inc,',
            'Copyright (c) 2014-2017 Georgia Institute of Technology.'
        ]
    )}
/** One operand shape of an instruction. Several encodings can share a shape; this is the shape. */
export type X86InstructionForm = {
    /** Operands as the documentation writes them, e.g. \`['r/m64', 'imm8']\`. */
    operands: string[]
    /** The oldest processor level this form needs, e.g. \`386\`, \`X86_64\`. Empty when unlabelled. */
    cpu: string
    /** Instruction set extensions the form belongs to, e.g. \`['SSE2']\`. */
    features: string[]
    /** Flags worth showing a reader: \`LOCK\`, \`NOLONG\`, \`PRIV\`, \`UNDOC\`, \`OBSOLETE\`. */
    notes: string[]
}

export type X86Instruction = {
    name: string
    /** NASM's own manual heading for this instruction, e.g. \`Jumps\`. */
    section: string
    /** The oldest processor level that can run any form of it. */
    cpu: string
    features: string[]
    /** One line, or empty when the Opcodes database does not cover the instruction. */
    summary: string
    forms: X86InstructionForm[]
}

export const X86_INSTRUCTIONS: X86Instruction[] = [
${instructions.map((instruction) => `    ${serialise(instruction)}`).join(',\n')}
]
`
)

writeFileSync(
    join(outDir, 'x86Mnemonics.ts'),
    `${header('Just the names, for the syntax highlighter and the language detector.', [
        ...NASM_SOURCE,
        '',
        'Separate from `x86Instructions.ts` so that highlighting a file does not pull the whole',
        'instruction table, its operand shapes and its flags into the editor bundle.'
    ])}
/** Every mnemonic the vendored NASM accepts, pseudo-ops excluded. */
export const X86_MNEMONICS: string[] = [
${instructions.map((instruction) => `    ${JSON.stringify(instruction.name)}`).join(',\n')}
]
`
)

writeFileSync(
    join(outDir, 'x86Descriptions.ts'),
    `${header(
        'What each instruction does, for the instructions an appendix of NASM once documented.',
        [
            'Prose: NASM\'s "x86 Instruction Reference" appendix (`doc/insref.src`), last shipped in',
            'nasm-2.05.01 and removed in 2.06. Copyright 1996-2008 the NASM Authors, under the LGPL that',
            'NASM carried at that release; NASM relicensed to BSD-2-Clause in 2.07. Converted from NASM',
            'documentation markup to markdown, otherwise unchanged.',
            '',
            'It predates long mode, so it describes behaviour and never operand forms: the forms come',
            'from the current table in `x86Instructions.ts`.'
        ]
    )}
export type X86Description = {
    /** The appendix's own heading, e.g. \`\\\`ADD\\\`: Add Integers\`. */
    title: string
    /** Markdown. */
    description: string
}

export const X86_DESCRIPTIONS: Record<string, X86Description> = {
${Object.entries(descriptions)
    .map(([name, entry]) => `    ${JSON.stringify(name)}: ${serialise(entry)}`)
    .join(',\n')}
}
`
)

writeFileSync(
    join(outDir, 'x86Syscalls.ts'),
    `${header(
        'The Linux syscalls this emulator implements, which is a shorter list than Linux defines.',
        [
            'blink (`emulators/x86/libblink`), SPDX-License-Identifier: ISC,',
            'Copyright 2022 Justine Alexandra Roberts Tunney.',
            '',
            "Numbers, names and argument shapes come from blink's dispatch table and its strace",
            'signatures, so a call listed here is a call that works in the editor.'
        ]
    )}
export type X86Syscall = {
    /** The value \`rax\` holds when the \`syscall\` instruction runs. */
    number: number
    name: string
    /** How many arguments the call reads, in register order: rdi, rsi, rdx, r10, r8, r9. */
    arity: number
    /** What each argument is, where blink's trace signature says. Empty for the untraced calls. */
    args: string[]
    /** True when the call can wait for the outside world, e.g. \`read\` on the console. */
    blocking: boolean
}

export const X86_SYSCALLS: X86Syscall[] = [
${syscalls
    .map((syscall) =>
        serialise({
            number: syscall.number,
            name: syscall.name,
            arity: syscall.arity,
            args: syscall.args,
            blocking: syscall.blocking
        })
    )
    .map((line) => `    ${line}`)
    .join(',\n')}
]
`
)

const prefixGroups = tokens.filter((group) => group.kind === 'TOKEN_PREFIX')
const sizeGroup = tokens.find((group) => group.kind === 'TOKEN_SIZE')
const specialGroup = tokens.find((group) => group.kind === 'TOKEN_SPECIAL')

writeFileSync(
    join(outDir, 'x86Tokens.ts'),
    `${header('The words NASM accepts that are not instructions: directives, prefixes, specifiers.', NASM_SOURCE)}
/** Assembler directives, e.g. \`section\`, \`global\`, \`bits\`. */
export const X86_DIRECTIVES: string[] = ${serialise(directives)}

/** Every register name the assembler accepts, general purpose through vector and system. */
export const X86_ASSEMBLER_REGISTERS: string[] = ${serialise(registers)}

/** Directives NASM implements as standard macros, e.g. \`struc\`, \`align\`, \`global\`. */
export const X86_STANDARD_MACROS: string[] = ${serialise(standardMacros)}

/** Preprocessor directives, e.g. \`%define\`, \`%macro\`, \`%ifdef\`. */
export const X86_PREPROCESSOR_DIRECTIVES: string[] = ${serialise(preprocessor)}

/** Pseudo-ops that reserve or emit data, e.g. \`db\`, \`resq\`, \`equ\`. */
export const X86_PSEUDO_OPS: string[] = ${serialise(readNasmNames().filter((name) => PSEUDO.test(name)))}

/** Instruction prefixes, e.g. \`lock\`, \`rep\`, \`o64\`. */
export const X86_PREFIXES: string[] = ${serialise([...new Set(prefixGroups.flatMap((group) => group.tokens))])}

/** Operand size specifiers, e.g. \`byte\`, \`qword\`. */
export const X86_SIZE_SPECIFIERS: string[] = ${serialise(sizeGroup?.tokens ?? [])}

/** Address and branch keywords, e.g. \`near\`, \`far\`, \`abs\`. */
export const X86_ADDRESS_KEYWORDS: string[] = ${serialise(specialGroup?.tokens ?? [])}

/** What each instruction flag means, for the badges on an instruction page. */
export const X86_FLAG_MEANINGS: Record<string, string> = ${serialise(
        Object.fromEntries(
            [...flagMeanings.entries()]
                .filter(
                    ([name]) =>
                        NOTABLE_FLAGS.has(name) || flagMeanings.get(name).group !== 'encoding'
                )
                .map(([name, meaning]) => [name, meaning.description])
        )
    )}
`
)

/**
 * What the editor will publish: the integer sections, minus anything that needs an extension in
 * every form, which is the rule `X86-documentation.ts` applies. Printed here so the design doc's
 * coverage numbers come from the command that produces the files.
 */
const DOCUMENTED_SECTIONS = new Set([
    'Integer data move instructions',
    'Load effective address',
    'The basic 8 arithmetic operations',
    'Bitwise testing',
    'The basic shift and rotate operations',
    'Other basic integer arithmetic',
    'Double width shift',
    'Sign and zero extension',
    'Bit operations',
    'Endianness handling',
    'Decimal arithmetic',
    'Atomic operations',
    'Stack operations',
    'Jumps',
    'Conditional instructions',
    'Call and return',
    'Interrupts, system calls, and returns',
    'Flag register instructions',
    'String instructions',
    'No operation'
])
const documented = instructions.filter(
    (instruction) =>
        DOCUMENTED_SECTIONS.has(instruction.section) && instruction.features.length === 0
)
const documentedProse = documented.filter((instruction) => descriptions[instruction.name])

const forms = instructions.reduce((count, instruction) => count + instruction.forms.length, 0)
console.log(`x86Instructions.ts  ${instructions.length} instructions, ${forms} operand shapes`)
console.log(`x86Mnemonics.ts     ${instructions.length} names`)
console.log(`x86Descriptions.ts  ${Object.keys(descriptions).length} descriptions`)
console.log(`x86Syscalls.ts      ${syscalls.length} syscalls`)
console.log(
    `x86Tokens.ts        ${directives.length} directives, ${standardMacros.length} standard macros, ${preprocessor.length} preprocessor directives, ${registers.length} registers`
)
console.log(
    `documented set      ${documented.length} instructions, ${documentedProse.length} with prose (${((documentedProse.length / documented.length) * 100).toFixed(1)}%)`
)
