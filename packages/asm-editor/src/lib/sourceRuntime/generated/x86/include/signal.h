typedef int sig_atomic_t;          /* An integer a handler can set and the program read. */
typedef void (*sighandler_t)(int); /* A handler: a function that takes the signal's number. */

#define SIG_DFL ((sighandler_t)0)  /* The signal's default action: SIGINT ends the program. */
#define SIG_IGN ((sighandler_t)1)  /* Ignore the signal. */
#define SIG_ERR ((sighandler_t)-1) /* What signal returns when it fails. */

/* sigprocmask's how. */
#define SIG_BLOCK   0 /* Block the signals of the set too. */
#define SIG_UNBLOCK 1 /* Stop blocking them. */
#define SIG_SETMASK 2 /* Block exactly them. */

/* sa_flags: how a handler runs. */
#define SA_NOCLDSTOP 0x1
#define SA_NOCLDWAIT 0x2
#define SA_SIGINFO   0x4        /* The handler is sa_sigaction, which also gets a siginfo_t. */
#define SA_ONSTACK   0x8000000
/* A read or wait the signal interrupts starts over instead of failing with EINTR. */
#define SA_RESTART   0x10000000
#define SA_NODEFER   0x40000000 /* Do not block the signal while its handler runs. */
#define SA_RESETHAND 0x80000000 /* Handle the signal once, then go back to SIG_DFL. */
/*
 * The kernel's, not in the C library's header: sa_restorer holds what a handler returns to.
 * rt_sigaction refuses a handler without it, and sigaction sets it for you.
 */
#define SA_RESTORER  0x4000000

/**
 * A set of signals, one bit each: signal n is bit (n - 1) % 64 of __val[(n - 1) / 64]. Change it
 * with sigemptyset, sigaddset and the rest.
 */
typedef struct {
    unsigned long __val[16];
} sigset_t;

/** A value sent along with a signal. */
union sigval {
    int sival_int;
    void *sival_ptr;
};

struct __aed_siginfo_kill {
    pid_t si_pid;
    uid_t si_uid;
};

struct __aed_siginfo_rt {
    pid_t si_pid;
    uid_t si_uid;
    union sigval si_sigval;
};

struct __aed_siginfo_fault {
    void *si_addr;
};

union __aed_siginfo_fields {
    int _pad[28];
    struct __aed_siginfo_kill _kill;
    struct __aed_siginfo_rt _rt;
    struct __aed_siginfo_fault _sigfault;
};

/**
 * What a handler with SA_SIGINFO gets about the signal: its number, why it came (si_code) and from
 * whom, si_pid, or for SIGSEGV the address, si_addr.
 */
typedef struct {
    int si_signo;                         /* The signal's number. */
    int si_errno;
    int si_code;                          /* Why it came. */
    int __pad0;
    union __aed_siginfo_fields _sifields; /* The rest, by si_code. */
} siginfo_t;

/** Who sent it, for kill and raise. */
#define si_pid _sifields._kill.si_pid
#define si_uid _sifields._kill.si_uid
#define si_value _sifields._rt.si_sigval
#define si_int _sifields._rt.si_sigval.sival_int
#define si_ptr _sifields._rt.si_sigval.sival_ptr

/** For SIGSEGV, the address touched. */
#define si_addr _sifields._sigfault.si_addr

union __aed_sigaction_handler {
    sighandler_t sa_handler;
    void (*sa_sigaction)(int, siginfo_t *, void *);
};

/**
 * What sigaction takes and gives back: the handler, the signals blocked while it runs, and how it
 * runs. The C library's layout; sigaction makes the kernel's from it.
 */
struct sigaction {
    union __aed_sigaction_handler __sigaction_handler; /* sa_handler, or sa_sigaction. */
    /* The signals blocked while the handler runs, besides its own. */
    sigset_t sa_mask;
    int sa_flags;                                      /* SA_RESTART, SA_SIGINFO, ... */
    void (*sa_restorer)(void);                         /* Set by sigaction. */
};

/** The handler, which takes the signal's number. */
#define sa_handler __sigaction_handler.sa_handler

/** With SA_SIGINFO, the handler that also gets a siginfo_t and the context. */
#define sa_sigaction __sigaction_handler.sa_sigaction

/**
 * What the rt_sigaction system call takes, which sigaction makes from a struct sigaction. In
 * assembly: k_sa_handler the handler, sa_flags with SA_RESTORER, sa_restorer the code the handler
 * returns to, and 8, the size of sa_mask, as rt_sigaction's fourth argument.
 */
struct kernel_sigaction {
    void *k_sa_handler;     /* The handler, or SIG_DFL or SIG_IGN. */
    unsigned long sa_flags; /* SA_RESTORER and the others. */
    void *sa_restorer;      /* Code that makes rt_sigreturn. */
    unsigned long sa_mask;  /* The signals blocked while the handler runs. */
};

/**
 * What a handler returns to: the rt_sigreturn system call, which puts back what the program was
 * doing when the signal came. sigaction registers it, as the C library registers its own. It has no
 * prologue, since it runs on the signal's frame.
 */
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wattributes"
__attribute__((naked)) static inline void __aed_restore_rt(void) {
    __asm__("mov eax, 15\n\tsyscall"); /* rt_sigreturn */
}
#pragma GCC diagnostic pop

/** Empties *set. Returns 0. */
static inline int sigemptyset(sigset_t *set) {
    unsigned __i;
    if (!set) return (int)__aed_syscall_return(-22); /* EINVAL */
    for (__i = 0; __i < 16; __i++) set->__val[__i] = 0;
    return 0;
}

/** Puts every signal in *set, but 32 and 33, which the C library keeps for itself. Returns 0. */
static inline int sigfillset(sigset_t *set) {
    unsigned __i;
    if (!set) return (int)__aed_syscall_return(-22); /* EINVAL */
    for (__i = 0; __i < 16; __i++) set->__val[__i] = ~0UL;
    set->__val[0] &= ~(3UL << 31);
    return 0;
}

