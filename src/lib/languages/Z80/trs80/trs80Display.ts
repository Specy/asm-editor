/**
 * Every character rasterized once: 256 glyphs of `TRS80_CELL`, one byte per pixel, non-zero for
 * ink. Painting a cell is then a copy rather than a bit test per pixel, which is what makes a
 * full-screen flush affordable.
 *
 * Characters 128 to 191 are the block graphics and carry no glyph data: the low six bits of the
 * character are the 2 by 3 block itself, bit 0 top-left, then across and down.
 */
export function buildGlyphSheet(): Uint8Array {
    const { width, height } = TRS80_CELL
    const sheet = new Uint8Array(256 * width * height)
    for (let code = 0; code < 256; code++) {
        const bank = GLYPH_BANKS[code >> 6]
        const base = code * width * height
        for (let y = 0; y < height; y++) {
            for (let x = 0; x < width; x++) {
                let ink: boolean
                if (bank === -1) {
                    //the character is the block: two columns by three rows of the cell
                    const bit = Math.floor(y / (height / 3)) * 2 + Math.floor(x / (width / 2))
                    ink = ((code % 64) & (1 << bit)) !== 0
                } else {
                    const row = GLYPHS[(bank + (code % 64)) * GLYPH_ROWS + (y >> 1)]
                    ink = (row & (1 << x)) !== 0
                }
                if (ink) sheet[base + y * width + x] = 1
            }
        }
    }
    return sheet
}

