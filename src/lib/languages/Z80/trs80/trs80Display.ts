/**
 * The TRS-80 Model III display and keyboard, as plain data: the memory map a program stores into,
 * the character generator's glyphs, the block-graphics rule and the keyboard matrix.
 *
 * This is the one Z80 graphics interface in this editor that is not this project's own invention
 * ([ADR 0020](../../../../../docs/adr/0020-mirror-the-trs80-display-in-guest-memory.md)): it is the
 * machine `@specy/z80` descends from, so programs written elsewhere for it draw here unchanged.
 *
 * The glyphs are `GLYPH_CG4` from the fork's own submodule
 * (`emulators/z80/packages/trs80-emulator-web/src/Fonts.ts`, MIT, compatible with this
 * repository's AGPL), a dump of the Model III character generator. They are copied rather than
 * imported because that module lives in a package that pulls in the DOM, while this one has to load
 * under node and during prerendering. One glyph is 12 bytes, one per row from the top, and bit 0 is
 * the leftmost pixel; each row is drawn twice, which is what makes the cell 24 pixels tall.
 *
 * Plain TypeScript: no runes, no DOM, and nothing from the emulator.
 */

// ------------------------------------------------------------------ memory map

/** Video RAM: one byte per character cell, the bytes a program stores to put something on screen. */
export const TRS80_VIDEO_BEGIN = 0x3c00
export const TRS80_VIDEO_END = 0x4000

/** The keyboard matrix, four mirrored banks of 256 below video RAM. */
export const TRS80_KEYBOARD_BEGIN = 0x3800
export const TRS80_KEYBOARD_END = 0x3c00

export const TRS80_COLUMNS = 64
export const TRS80_ROWS = 16
export const TRS80_VIDEO_SIZE = TRS80_COLUMNS * TRS80_ROWS

/**
 * What the ROM's clear fills video RAM with. Zeroed memory would otherwise open on 1024 copies of
 * glyph 0 rather than on a blank screen.
 */
export const TRS80_BLANK_CELL = 0x20

/** The Model III's cell. The glyph data is 12 rows and each is drawn twice. */
export const TRS80_CELL: ScreenCellSize = { width: 8, height: 24 }

/** 64 by 16 cells of 8 by 24 pixels: the machine's own geometry, and 4:3 as it was. */
export const TRS80_SCREEN_WIDTH = TRS80_COLUMNS * TRS80_CELL.width
export const TRS80_SCREEN_HEIGHT = TRS80_ROWS * TRS80_CELL.height

/**
 * The chunky graphics pixels of the block characters: each cell is 2 across by 3 down, so the whole
 * screen is 128 by 48. There is no other pixel mode on the machine — the hi-res cards are not
 * emulated upstream either.
 */
export const TRS80_GRAPHICS_WIDTH = TRS80_COLUMNS * 2
export const TRS80_GRAPHICS_HEIGHT = TRS80_ROWS * 3

/** Whether an address is one of the 1024 cells. */
export function isVideoAddress(address: number): boolean {
    return address >= TRS80_VIDEO_BEGIN && address < TRS80_VIDEO_END
}

/** Whether an address is in the keyboard matrix. */
export function isKeyboardAddress(address: number): boolean {
    return address >= TRS80_KEYBOARD_BEGIN && address < TRS80_KEYBOARD_END
}

