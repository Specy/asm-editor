/**
 * The rows of one glyph at a cell height, top first, with bit 0 the leftmost pixel. A cell taller
 * than the 8 source rows repeats each row, so the 8 by 16 cell is the 8 by 8 one at double height
 * and both cells show the same shapes.
 */
export function glyphRows(code: number, cellHeight: number): number[] {
    const glyph = GLYPHS[code - FIRST_CODE] ?? BLANK_GLYPH
    const rows: number[] = []
    for (let row = 0; row < cellHeight; row++) {
        rows.push(glyph[Math.floor((row * FONT_ROWS) / cellHeight)] ?? 0)
    }
    return rows
}

/** Whether the font has a shape for a code point; everything else draws as a blank cell. */
export function hasGlyph(code: number): boolean {
    return code >= FIRST_CODE && code < FIRST_CODE + GLYPHS.length
}
