/**
 * The Screen's fixed-cell font. Text and graphics share one image ([ADR 0003](../../../../../docs/adr/0003-preserve-simulator-graphics-conventions.md)),
 * so the text cursor needs a font that rasterizes to whole pixels at a known cell size rather than
 * a browser font whose metrics depend on the host.
 *
 * The glyphs are the public domain 8x8 font from Daniel Hepper's `font8x8` collection
 * (https://github.com/dhepper/font8x8, `font8x8_basic.h`), which descends from the 8x8 font Marcel
 * Sondaar placed in the public domain. Public domain imposes no attribution or license terms, so it
 * cannot conflict with this repository's AGPL, and the same table can be quoted in documentation.
 *
 * One byte is one row, from the top, and bit 0 is the leftmost pixel — the order the original table
 * uses. Only 0x20 to 0x7F are covered: everything outside the table draws as a blank cell.
 */

export type ScreenCellSize = {
    readonly width: number
    readonly height: number
}

/** The Z80's cell: 32 columns by 24 rows on its default 256 by 192 Screen ([ADR 0011](../../../../../docs/adr/0011-z80-peripherals-through-the-port-map.md)). */
export const SCREEN_CELL_8X8: ScreenCellSize = { width: 8, height: 8 }

/** The M68K's cell: 80 columns by 30 rows on EASy68K's 640 by 480 default window. */
export const SCREEN_CELL_8X16: ScreenCellSize = { width: 8, height: 16 }

/** The source rows every cell size is derived from. */
export const FONT_ROWS = 8

